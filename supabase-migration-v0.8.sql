-- v0.8 待确认专区迁移
--
-- 背景：新增「待确认专区」后，AI 识别上传的卡片（is_confirmed = FALSE）
-- 会先进入待确认区，确认后才进入主网格分类。
--
-- 历史存量卡片全部标记为已确认（升级前上传的截图视为用户已认可），
-- 否则所有历史卡片会一次性全部涌进待确认区，主网格瞬间清空。
--
-- 在 Supabase SQL Editor 里执行一次即可，可重复执行（幂等）。
-- ═══════════════════════════════════════════════════════════════
UPDATE works
SET is_confirmed = TRUE, updated_at = NOW()
WHERE is_confirmed = FALSE;
